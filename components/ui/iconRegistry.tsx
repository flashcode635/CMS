/** Choices for the CMS icon picker (stable order, alphabetical by name). */
export const ICON_CHOICES: Array<{ name: string; Icon: LucideIcon }> = Object.entries(
  CMS_ICONS
).map(([name, Icon]) => ({ name, Icon }));

/** Resolve a kebab-case icon NAME to its lucide component (null when unknown). */
export function getLucideIcon(name?: string | null): LucideIcon | null {
  if (!name) return null;
  return CMS_ICONS[name.trim().toLowerCase()] ?? null;
}
